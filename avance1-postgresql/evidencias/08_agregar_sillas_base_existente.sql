-- =====================================================================
-- REELS CINEMA - Entrega final
-- 08_agregar_sillas_base_existente.sql
-- Agrega la venta con sillas a una base que YA estaba cargada con la
-- versión anterior de los scripts (13 tablas), SIN borrar sus datos:
--   1. tabla silla_venta y su índice
--   2. una silla para cada boleta ya vendida (ventas no canceladas)
--   3. triggers 13 y 14
--   4. procedimiento 7 (sp_registrar_venta_sillas)
-- En una base nueva no hace falta: 01 a 04 ya traen todo esto.
-- Se puede ejecutar más de una vez sin duplicar nada.
-- =====================================================================

-- 1. Tabla e índice
-- ---------------------------------------------------------------------
-- SILLA_VENTA (entrega final)
-- Silla asignada a cada boleta de una venta. Las salas se numeran en
-- filas de 10 sillas (A1..A10, B1..B10, ...): 8 filas en la sala de 80
-- puestos, 6 en la de 60 y 4 en la de 40.
-- La restricción UNIQUE (función, fila, número) impide que dos ventas
-- tomen la misma silla, incluso si llegan al mismo tiempo.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS silla_venta (
    id_silla_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id_venta INTEGER NOT NULL,
    funcion_id_funcion INTEGER NOT NULL,
    fila CHAR(1) NOT NULL,
    numero SMALLINT NOT NULL,
    CONSTRAINT fk_silla_venta_venta FOREIGN KEY (venta_id_venta)
        REFERENCES venta(id_venta) ON DELETE CASCADE,
    CONSTRAINT fk_silla_venta_funcion FOREIGN KEY (funcion_id_funcion)
        REFERENCES funcion(id_funcion),
    CONSTRAINT uq_silla_venta_funcion_silla UNIQUE (funcion_id_funcion, fila, numero),
    CONSTRAINT ck_silla_venta_fila CHECK (fila BETWEEN 'A' AND 'Z'),
    CONSTRAINT ck_silla_venta_numero CHECK (numero BETWEEN 1 AND 10)
);

-- Sillas: por venta (liberar sillas al cancelar). La restricción UNIQUE
-- ya crea el índice (función, fila, número) que usa el mapa de la sala.
CREATE INDEX IF NOT EXISTS idx_silla_venta_venta
    ON silla_venta (venta_id_venta);

-- 2. Sillas de las ventas existentes (antes de crear el trigger 13, que
--    no deja asignar sillas en funciones ya realizadas)
DROP TRIGGER IF EXISTS trg_silla_venta_validar ON silla_venta;
INSERT INTO silla_venta (venta_id_venta, funcion_id_funcion, fila, numero)
SELECT v.id_venta,
       v.funcion_id_funcion,
       CHR(65 + ((p.pos * 37 + v.funcion_id_funcion * 11) % v.capacidad) / 10),
       ((p.pos * 37 + v.funcion_id_funcion * 11) % v.capacidad) % 10 + 1
FROM (
    SELECT ve.id_venta, ve.funcion_id_funcion, ve.cantidad_boletas, s.capacidad,
           SUM(ve.cantidad_boletas) OVER (PARTITION BY ve.funcion_id_funcion
                                          ORDER BY ve.id_venta)::INTEGER - ve.cantidad_boletas AS desde
    FROM venta ve
    JOIN funcion f ON f.id_funcion = ve.funcion_id_funcion
    JOIN sala s ON s.id_sala = f.sala_id_sala
    WHERE ve.estado <> 'cancelada'
      AND NOT EXISTS (SELECT 1 FROM silla_venta sv WHERE sv.venta_id_venta = ve.id_venta)
) v
CROSS JOIN LATERAL generate_series(v.desde, v.desde + v.cantidad_boletas - 1) AS p(pos)
ORDER BY v.id_venta, p.pos;


-- 3. Triggers
-- ---------------------------------------------------------------------
-- 13. SILLA_VENTA: validar la silla asignada (entrega final)
-- Regla: la silla debe existir en la sala de la función (fila y número
-- dentro de la capacidad), la venta no puede estar cancelada, la función
-- debe estar programada y una venta no puede tener más sillas que
-- boletas. Si no se envía la función, se toma la de la venta.
-- (Que dos ventas no tomen la misma silla lo garantiza la restricción
-- UNIQUE uq_silla_venta_funcion_silla.)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_silla_venta_validar()
RETURNS TRIGGER AS $$
DECLARE
    v_venta     venta%ROWTYPE;
    v_estado_f  VARCHAR(20);
    v_capacidad INTEGER;
    v_posicion  INTEGER;
    v_asignadas INTEGER;
BEGIN
    SELECT * INTO v_venta FROM venta WHERE id_venta = NEW.venta_id_venta;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La venta % no existe', NEW.venta_id_venta;
    END IF;
    IF v_venta.estado = 'cancelada' THEN
        RAISE EXCEPTION 'La venta % está cancelada; no se le pueden asignar sillas', NEW.venta_id_venta;
    END IF;

    NEW.funcion_id_funcion := COALESCE(NEW.funcion_id_funcion, v_venta.funcion_id_funcion);
    IF NEW.funcion_id_funcion <> v_venta.funcion_id_funcion THEN
        RAISE EXCEPTION 'La venta % es de la función %, no de la función %',
            NEW.venta_id_venta, v_venta.funcion_id_funcion, NEW.funcion_id_funcion;
    END IF;

    SELECT f.estado, s.capacidad INTO v_estado_f, v_capacidad
    FROM funcion f JOIN sala s ON s.id_sala = f.sala_id_sala
    WHERE f.id_funcion = NEW.funcion_id_funcion;
    IF v_estado_f <> 'programada' THEN
        RAISE EXCEPTION 'La función % está "%"; no se asignan sillas', NEW.funcion_id_funcion, v_estado_f;
    END IF;

    NEW.fila := UPPER(NEW.fila);
    v_posicion := (ASCII(NEW.fila) - 65) * 10 + NEW.numero;
    IF NEW.numero NOT BETWEEN 1 AND 10 OR v_posicion > v_capacidad THEN
        RAISE EXCEPTION 'La silla % no existe en esta sala (capacidad %: filas A a %, sillas 1 a 10)',
            NEW.fila || NEW.numero, v_capacidad, CHR(64 + CEIL(v_capacidad / 10.0)::INTEGER);
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT COUNT(*) INTO v_asignadas FROM silla_venta WHERE venta_id_venta = NEW.venta_id_venta;
        IF v_asignadas >= v_venta.cantidad_boletas THEN
            RAISE EXCEPTION 'La venta % tiene % boleta(s) y ya tiene todas sus sillas asignadas',
                NEW.venta_id_venta, v_venta.cantidad_boletas;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_silla_venta_validar ON silla_venta;
CREATE TRIGGER trg_silla_venta_validar
BEFORE INSERT OR UPDATE ON silla_venta
FOR EACH ROW
EXECUTE FUNCTION fn_silla_venta_validar();


-- ---------------------------------------------------------------------
-- 14. VENTA: liberar las sillas de una venta cancelada (entrega final)
-- Regla: cuando una venta pasa a "cancelada" (por el cliente, por el
-- cierre diario o porque se canceló la función, trigger 8), sus sillas
-- quedan libres de inmediato para que otra persona las pueda comprar.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_venta_liberar_sillas()
RETURNS TRIGGER AS $$
DECLARE
    v_liberadas INTEGER;
BEGIN
    DELETE FROM silla_venta WHERE venta_id_venta = NEW.id_venta;
    GET DIAGNOSTICS v_liberadas = ROW_COUNT;
    IF v_liberadas > 0 THEN
        RAISE NOTICE 'Venta % cancelada: % silla(s) liberada(s)', NEW.id_venta, v_liberadas;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_venta_liberar_sillas ON venta;
CREATE TRIGGER trg_venta_liberar_sillas
AFTER UPDATE OF estado ON venta
FOR EACH ROW
WHEN (NEW.estado = 'cancelada' AND OLD.estado <> 'cancelada')
EXECUTE FUNCTION fn_venta_liberar_sillas();


-- 4. Procedimiento
-- ---------------------------------------------------------------------
-- 7. sp_registrar_venta_sillas  (venta con sillas - entrega final)
-- Propósito: vender boletas escogiendo las sillas, todo en una sola
-- transacción. Recibe las sillas como texto ('C5', 'C6', ...), registra
-- la venta con sp_registrar_venta (que valida espectador, función,
-- aforo, canal y precio) y luego guarda cada silla (trigger 13 y la
-- restricción UNIQUE). Si una silla ya está ocupada o no existe, se
-- deshace la venta completa: no queda una venta sin sus sillas.
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_registrar_venta_sillas(
    p_id_espectador   INTEGER,
    p_id_funcion      INTEGER,
    p_id_tipo_boleta  INTEGER,
    p_sillas          TEXT[],
    p_metodo_pago     VARCHAR,
    p_canal_venta     VARCHAR,
    p_id_staff        INTEGER DEFAULT NULL,
    INOUT p_id_venta  INTEGER DEFAULT NULL,
    INOUT p_total     NUMERIC DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_silla TEXT;
    v_fila  CHAR(1);
    v_num   INTEGER;
BEGIN
    IF p_sillas IS NULL OR CARDINALITY(p_sillas) = 0 THEN
        RAISE EXCEPTION 'Debe escoger al menos una silla';
    END IF;
    IF (SELECT COUNT(DISTINCT UPPER(BTRIM(s))) FROM UNNEST(p_sillas) s) <> CARDINALITY(p_sillas) THEN
        RAISE EXCEPTION 'Hay sillas repetidas en la selección';
    END IF;

    CALL sp_registrar_venta(p_id_espectador, p_id_funcion, p_id_tipo_boleta,
                            CARDINALITY(p_sillas), p_metodo_pago, p_canal_venta,
                            p_id_staff, p_id_venta, p_total);

    FOREACH v_silla IN ARRAY p_sillas LOOP
        v_silla := UPPER(BTRIM(v_silla));
        IF v_silla !~ '^[A-Z]([1-9]|10)$' THEN
            RAISE EXCEPTION 'Silla no válida: "%" (formato: letra y número, por ejemplo C7)', v_silla;
        END IF;
        v_fila := LEFT(v_silla, 1);
        v_num := SUBSTRING(v_silla FROM 2)::INTEGER;
        INSERT INTO silla_venta (venta_id_venta, funcion_id_funcion, fila, numero)
        VALUES (p_id_venta, p_id_funcion, v_fila, v_num);
    END LOOP;

    RAISE NOTICE 'Sillas de la venta %: %', p_id_venta, ARRAY_TO_STRING(p_sillas, ', ');

EXCEPTION
    WHEN unique_violation THEN
        RAISE EXCEPTION 'La silla % ya está ocupada en la función %; escoja otra', v_silla, p_id_funcion
            USING ERRCODE = 'unique_violation';
END;
$$;


-- Verificación: cada boleta vendida tiene su silla
SELECT (SELECT COALESCE(SUM(cantidad_boletas), 0) FROM venta WHERE estado <> 'cancelada') AS boletas_vendidas,
       (SELECT COUNT(*) FROM silla_venta) AS sillas_asignadas;
