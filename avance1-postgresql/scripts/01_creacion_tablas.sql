-- =====================================================================
-- REELS CINEMA - Avance 1
-- 01_creacion_tablas.sql
-- Creación de tablas, llaves primarias, llaves foráneas,
-- restricciones de integridad e índices básicos (PostgreSQL)
-- Versión corregida (entrega final): 16 tablas. Se agregan obra,
-- funcion_obra y venta_obra (teatro), silla_venta (silla de cada boleta),
-- producto y venta_producto (confitería) y la columna contrasena_hash en espectador y staff para el inicio de
-- sesión de la página web.
-- =====================================================================

-- ---------------------------------------------------------------------
-- SALA
-- ---------------------------------------------------------------------
CREATE TABLE sala (
    id_sala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_sala INTEGER NOT NULL UNIQUE,
    capacidad INTEGER NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'disponible',
    CONSTRAINT ck_sala_numero CHECK (numero_sala > 0),
    CONSTRAINT ck_sala_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_sala_estado CHECK (
        estado IN ('disponible', 'mantenimiento', 'fuera_servicio')
    )
);

-- ---------------------------------------------------------------------
-- ESPECTADOR
-- ---------------------------------------------------------------------
CREATE TABLE espectador (
    id_espectador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    telefono VARCHAR(25) NOT NULL,
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(15) NOT NULL DEFAULT 'activo',
    contrasena_hash VARCHAR(200),
    CONSTRAINT ck_espectador_nombre CHECK (BTRIM(nombre_completo) <> ''),
    CONSTRAINT ck_espectador_correo CHECK (BTRIM(correo) <> ''),
    CONSTRAINT ck_espectador_telefono CHECK (BTRIM(telefono) <> ''),
    CONSTRAINT ck_espectador_estado CHECK (estado IN ('activo', 'inactivo'))
);

-- ---------------------------------------------------------------------
-- STAFF
-- ---------------------------------------------------------------------
CREATE TABLE staff (
    id_staff INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(30) NOT NULL,
    cargo VARCHAR(30) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    telefono VARCHAR(25) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'activo',
    contrasena_hash VARCHAR(200),
    CONSTRAINT uq_staff_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT ck_staff_nombre CHECK (BTRIM(nombre_completo) <> ''),
    CONSTRAINT ck_staff_tipo_documento CHECK (BTRIM(tipo_documento) <> ''),
    CONSTRAINT ck_staff_documento CHECK (BTRIM(numero_documento) <> ''),
    CONSTRAINT ck_staff_correo CHECK (BTRIM(correo) <> ''),
    CONSTRAINT ck_staff_telefono CHECK (BTRIM(telefono) <> ''),
    CONSTRAINT ck_staff_cargo CHECK (
        cargo IN ('taquillero', 'administrador', 'proyeccionista', 'auxiliar')
    ),
    CONSTRAINT ck_staff_estado CHECK (estado IN ('activo', 'inactivo'))
);

-- ---------------------------------------------------------------------
-- TIPO_BOLETA
-- ---------------------------------------------------------------------
CREATE TABLE tipo_boleta (
    id_tipo_boleta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL,
    precio NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_tipo_boleta_categoria CHECK (BTRIM(categoria) <> ''),
    CONSTRAINT ck_tipo_boleta_descripcion CHECK (BTRIM(descripcion) <> ''),
    CONSTRAINT ck_tipo_boleta_precio CHECK (precio > 0)
);

-- ---------------------------------------------------------------------
-- PELICULA
-- ---------------------------------------------------------------------
CREATE TABLE pelicula (
    id_pelicula INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    duracion INTEGER NOT NULL,
    genero VARCHAR(50) NOT NULL,
    clasificacion_edad VARCHAR(30) NOT NULL,
    idioma_original VARCHAR(50) NOT NULL,
    fecha_estreno DATE NOT NULL,
    CONSTRAINT ck_pelicula_titulo CHECK (BTRIM(titulo) <> ''),
    CONSTRAINT ck_pelicula_duracion CHECK (duracion > 0),
    CONSTRAINT ck_pelicula_genero CHECK (BTRIM(genero) <> ''),
    CONSTRAINT ck_pelicula_clasificacion CHECK (BTRIM(clasificacion_edad) <> ''),
    CONSTRAINT ck_pelicula_idioma CHECK (BTRIM(idioma_original) <> '')
);

-- ---------------------------------------------------------------------
-- ACTORES_DIRECTORES
-- ---------------------------------------------------------------------
CREATE TABLE actores_directores (
    id_artista INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    nacionalidad VARCHAR(60) NOT NULL,
    rol VARCHAR(15) NOT NULL,
    biografia TEXT NOT NULL,
    CONSTRAINT ck_artista_nombre CHECK (BTRIM(nombre_completo) <> ''),
    CONSTRAINT ck_artista_nacionalidad CHECK (BTRIM(nacionalidad) <> ''),
    CONSTRAINT ck_artista_biografia CHECK (BTRIM(biografia) <> ''),
    CONSTRAINT ck_artista_rol CHECK (rol IN ('actor', 'director', 'ambos'))
);

-- ---------------------------------------------------------------------
-- FUNCION
-- ---------------------------------------------------------------------
CREATE TABLE funcion (
    id_funcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id_sala INTEGER NOT NULL,
    pelicula_id_pelicula INTEGER NOT NULL,
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    formato_proyeccion VARCHAR(10) NOT NULL,
    idioma_proyeccion VARCHAR(50) NOT NULL,
    subtitulada BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(20) NOT NULL DEFAULT 'programada',
    CONSTRAINT fk_funcion_sala FOREIGN KEY (sala_id_sala)
        REFERENCES sala(id_sala),
    CONSTRAINT fk_funcion_pelicula FOREIGN KEY (pelicula_id_pelicula)
        REFERENCES pelicula(id_pelicula),
    CONSTRAINT ck_funcion_horario CHECK (fecha_hora_fin > fecha_hora_inicio),
    CONSTRAINT ck_funcion_formato CHECK (formato_proyeccion IN ('2D', '3D')),
    CONSTRAINT ck_funcion_idioma CHECK (BTRIM(idioma_proyeccion) <> ''),
    CONSTRAINT ck_funcion_estado CHECK (
        estado IN ('programada', 'cancelada', 'finalizada')
    )
);

-- ---------------------------------------------------------------------
-- VENTA
-- ---------------------------------------------------------------------
CREATE TABLE venta (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espectador_id_espectador INTEGER NOT NULL,
    funcion_id_funcion INTEGER NOT NULL,
    tipo_boleta_id_tipo_boleta INTEGER NOT NULL,
    staff_id_staff INTEGER,
    fecha_hora_venta TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad_boletas INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    total NUMERIC(14,2) GENERATED ALWAYS AS
        (cantidad_boletas * precio_unitario) STORED,
    metodo_pago VARCHAR(20) NOT NULL,
    canal_venta VARCHAR(15) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'pendiente',
    CONSTRAINT fk_venta_espectador FOREIGN KEY (espectador_id_espectador)
        REFERENCES espectador(id_espectador),
    CONSTRAINT fk_venta_funcion FOREIGN KEY (funcion_id_funcion)
        REFERENCES funcion(id_funcion),
    CONSTRAINT fk_venta_tipo_boleta FOREIGN KEY (tipo_boleta_id_tipo_boleta)
        REFERENCES tipo_boleta(id_tipo_boleta),
    CONSTRAINT fk_venta_staff FOREIGN KEY (staff_id_staff)
        REFERENCES staff(id_staff),
    CONSTRAINT ck_venta_cantidad CHECK (cantidad_boletas > 0),
    CONSTRAINT ck_venta_precio CHECK (precio_unitario > 0),
    CONSTRAINT ck_venta_metodo CHECK (
        metodo_pago IN ('efectivo', 'tarjeta', 'transferencia')
    ),
    CONSTRAINT ck_venta_canal CHECK (canal_venta IN ('taquilla', 'en_linea')),
    CONSTRAINT ck_venta_estado CHECK (estado IN ('pendiente', 'pagada', 'cancelada')),
    CONSTRAINT ck_venta_staff_taquilla CHECK (
        canal_venta <> 'taquilla' OR staff_id_staff IS NOT NULL
    )
);

-- ---------------------------------------------------------------------
-- CONTRATO
-- ---------------------------------------------------------------------
CREATE TABLE contrato (
    id_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actores_directores_id_artista INTEGER NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    descripcion TEXT NOT NULL,
    valor NUMERIC(14,2) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'borrador',
    CONSTRAINT fk_contrato_artista FOREIGN KEY (actores_directores_id_artista)
        REFERENCES actores_directores(id_artista),
    CONSTRAINT ck_contrato_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_contrato_descripcion CHECK (BTRIM(descripcion) <> ''),
    CONSTRAINT ck_contrato_valor CHECK (valor > 0),
    CONSTRAINT ck_contrato_estado CHECK (
        estado IN ('borrador', 'vigente', 'finalizado', 'cancelado')
    )
);

-- ---------------------------------------------------------------------
-- PELICULA_ACTORES_DIRECTORES (tabla intermedia N:M)
-- ---------------------------------------------------------------------
CREATE TABLE pelicula_actores_directores (
    pelicula_id_pelicula INTEGER NOT NULL,
    actores_directores_id_artista INTEGER NOT NULL,
    CONSTRAINT pk_pelicula_actores_directores PRIMARY KEY
        (pelicula_id_pelicula, actores_directores_id_artista),
    CONSTRAINT fk_pelicula_artista_pelicula FOREIGN KEY (pelicula_id_pelicula)
        REFERENCES pelicula(id_pelicula),
    CONSTRAINT fk_pelicula_artista_artista FOREIGN KEY (actores_directores_id_artista)
        REFERENCES actores_directores(id_artista)
);

-- ---------------------------------------------------------------------
-- OBRA (obras de teatro que también se presentan en las salas)
-- ---------------------------------------------------------------------
CREATE TABLE obra (
    id_obra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL UNIQUE,
    autor_compania VARCHAR(150) NOT NULL,
    genero VARCHAR(50) NOT NULL,
    duracion INTEGER NOT NULL,
    clasificacion_edad VARCHAR(30) NOT NULL,
    sinopsis TEXT NOT NULL,
    fecha_estreno DATE NOT NULL,
    CONSTRAINT ck_obra_titulo CHECK (BTRIM(titulo) <> ''),
    CONSTRAINT ck_obra_autor CHECK (BTRIM(autor_compania) <> ''),
    CONSTRAINT ck_obra_genero CHECK (BTRIM(genero) <> ''),
    CONSTRAINT ck_obra_duracion CHECK (duracion > 0),
    CONSTRAINT ck_obra_clasificacion CHECK (BTRIM(clasificacion_edad) <> ''),
    CONSTRAINT ck_obra_sinopsis CHECK (BTRIM(sinopsis) <> '')
);

-- ---------------------------------------------------------------------
-- FUNCION_OBRA (presentación de una obra en una sala)
-- ---------------------------------------------------------------------
CREATE TABLE funcion_obra (
    id_funcion_obra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id_obra INTEGER NOT NULL,
    sala_id_sala INTEGER NOT NULL,
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'programada',
    CONSTRAINT fk_funcion_obra_obra FOREIGN KEY (obra_id_obra)
        REFERENCES obra(id_obra),
    CONSTRAINT fk_funcion_obra_sala FOREIGN KEY (sala_id_sala)
        REFERENCES sala(id_sala),
    CONSTRAINT ck_funcion_obra_horario CHECK (fecha_hora_fin > fecha_hora_inicio),
    CONSTRAINT ck_funcion_obra_estado CHECK (
        estado IN ('programada', 'cancelada', 'finalizada')
    )
);

-- ---------------------------------------------------------------------
-- VENTA_OBRA (boletas de teatro)
-- ---------------------------------------------------------------------
CREATE TABLE venta_obra (
    id_venta_obra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    espectador_id_espectador INTEGER NOT NULL,
    funcion_obra_id_funcion_obra INTEGER NOT NULL,
    tipo_boleta_id_tipo_boleta INTEGER NOT NULL,
    fecha_hora_venta TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad_boletas INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    total NUMERIC(14,2) GENERATED ALWAYS AS
        (cantidad_boletas * precio_unitario) STORED,
    metodo_pago VARCHAR(20) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'pagada',
    CONSTRAINT fk_venta_obra_espectador FOREIGN KEY (espectador_id_espectador)
        REFERENCES espectador(id_espectador),
    CONSTRAINT fk_venta_obra_funcion FOREIGN KEY (funcion_obra_id_funcion_obra)
        REFERENCES funcion_obra(id_funcion_obra),
    CONSTRAINT fk_venta_obra_tipo_boleta FOREIGN KEY (tipo_boleta_id_tipo_boleta)
        REFERENCES tipo_boleta(id_tipo_boleta),
    CONSTRAINT ck_venta_obra_cantidad CHECK (cantidad_boletas BETWEEN 1 AND 10),
    CONSTRAINT ck_venta_obra_precio CHECK (precio_unitario > 0),
    CONSTRAINT ck_venta_obra_metodo CHECK (
        metodo_pago IN ('efectivo', 'tarjeta', 'transferencia')
    ),
    CONSTRAINT ck_venta_obra_estado CHECK (estado IN ('pendiente', 'pagada', 'cancelada'))
);

-- ---------------------------------------------------------------------
-- SILLA_VENTA (entrega final)
-- Silla asignada a cada boleta de una venta. Las salas se numeran en
-- filas de 10 sillas (A1..A10, B1..B10, ...): 8 filas en la sala de 80
-- puestos, 6 en la de 60 y 4 en la de 40.
-- La restricción UNIQUE (función, fila, número) impide que dos ventas
-- tomen la misma silla, incluso si llegan al mismo tiempo.
-- ---------------------------------------------------------------------
CREATE TABLE silla_venta (
    id_silla_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id_venta INTEGER NOT NULL,
    funcion_id_funcion INTEGER NOT NULL,
    fila CHAR(1) NOT NULL,
    numero SMALLINT NOT NULL,
    CONSTRAINT fk_silla_venta_venta FOREIGN KEY (venta_id_venta)
        REFERENCES venta(id_venta) ON DELETE CASCADE,
    CONSTRAINT fk_silla_venta_funcion FOREIGN KEY (funcion_id_funcion)
        REFERENCES funcion(id_funcion),
    CONSTRAINT uq_silla_venta_funcion_silla UNIQUE (funcion_id_funcion, fila, numero),
    CONSTRAINT ck_silla_venta_fila CHECK (fila BETWEEN 'A' AND 'Z'),
    CONSTRAINT ck_silla_venta_numero CHECK (numero BETWEEN 1 AND 10)
);

-- ---------------------------------------------------------------------
-- PRODUCTO (entrega final)
-- Catálogo de la confitería: combos, crispetas, bebidas, dulces y snacks.
-- ---------------------------------------------------------------------
CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    categoria VARCHAR(20) NOT NULL,
    descripcion VARCHAR(200) NOT NULL,
    precio NUMERIC(12,2) NOT NULL,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_producto_categoria CHECK (
        categoria IN ('combo', 'crispetas', 'bebida', 'dulce', 'snack')
    ),
    CONSTRAINT ck_producto_precio CHECK (precio > 0),
    CONSTRAINT ck_producto_nombre CHECK (BTRIM(nombre) <> '')
);

-- ---------------------------------------------------------------------
-- VENTA_PRODUCTO (entrega final)
-- Productos de confitería comprados junto con una venta de boletas. El
-- precio se copia del catálogo en el momento de la compra (trigger 15).
-- ---------------------------------------------------------------------
CREATE TABLE venta_producto (
    id_venta_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id_venta INTEGER NOT NULL,
    producto_id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(14,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    CONSTRAINT fk_venta_producto_venta FOREIGN KEY (venta_id_venta)
        REFERENCES venta(id_venta) ON DELETE CASCADE,
    CONSTRAINT fk_venta_producto_producto FOREIGN KEY (producto_id_producto)
        REFERENCES producto(id_producto),
    CONSTRAINT uq_venta_producto UNIQUE (venta_id_venta, producto_id_producto),
    CONSTRAINT ck_venta_producto_cantidad CHECK (cantidad BETWEEN 1 AND 20),
    CONSTRAINT ck_venta_producto_precio CHECK (precio_unitario > 0)
);

-- =====================================================================
-- ÍNDICES BÁSICOS
-- PostgreSQL crea índices automáticamente para PRIMARY KEY y UNIQUE,
-- pero NO para las llaves foráneas. Estos índices aceleran los JOIN,
-- las validaciones de los triggers y los reportes.
-- (Si las tablas ya existen, basta con ejecutar solo esta sección.)
-- =====================================================================

-- Funciones: búsqueda por sala y horario (validación de cruces de horario)
CREATE INDEX IF NOT EXISTS idx_funcion_sala_inicio
    ON funcion (sala_id_sala, fecha_hora_inicio);
CREATE INDEX IF NOT EXISTS idx_funcion_pelicula
    ON funcion (pelicula_id_pelicula);

-- Ventas: llaves foráneas y reportes por fecha
CREATE INDEX IF NOT EXISTS idx_venta_funcion
    ON venta (funcion_id_funcion);
CREATE INDEX IF NOT EXISTS idx_venta_espectador
    ON venta (espectador_id_espectador);
CREATE INDEX IF NOT EXISTS idx_venta_tipo_boleta
    ON venta (tipo_boleta_id_tipo_boleta);
CREATE INDEX IF NOT EXISTS idx_venta_staff
    ON venta (staff_id_staff);
CREATE INDEX IF NOT EXISTS idx_venta_fecha
    ON venta (fecha_hora_venta);

-- Contratos por artista
CREATE INDEX IF NOT EXISTS idx_contrato_artista
    ON contrato (actores_directores_id_artista);

-- Tabla intermedia: la PK cubre (pelicula, artista); este índice cubre
-- la búsqueda inversa (películas de un artista)
CREATE INDEX IF NOT EXISTS idx_pad_artista
    ON pelicula_actores_directores (actores_directores_id_artista);

-- Búsqueda de espectadores por correo (sin distinguir mayúsculas)
CREATE INDEX IF NOT EXISTS idx_espectador_correo
    ON espectador (LOWER(correo));

-- Teatro: funciones por obra y por sala/horario, ventas por función y espectador
CREATE INDEX IF NOT EXISTS idx_funcion_obra_obra
    ON funcion_obra (obra_id_obra);
CREATE INDEX IF NOT EXISTS idx_funcion_obra_sala_inicio
    ON funcion_obra (sala_id_sala, fecha_hora_inicio);
CREATE INDEX IF NOT EXISTS idx_venta_obra_funcion
    ON venta_obra (funcion_obra_id_funcion_obra);
CREATE INDEX IF NOT EXISTS idx_venta_obra_espectador
    ON venta_obra (espectador_id_espectador);

-- Sillas: por venta (liberar sillas al cancelar). La restricción UNIQUE
-- ya crea el índice (función, fila, número) que usa el mapa de la sala.
CREATE INDEX IF NOT EXISTS idx_silla_venta_venta
    ON silla_venta (venta_id_venta);

-- Confitería: productos de cada venta (la restricción UNIQUE ya cubre la
-- búsqueda por venta) y ventas de cada producto (reporte de confitería)
CREATE INDEX IF NOT EXISTS idx_venta_producto_producto
    ON venta_producto (producto_id_producto);
